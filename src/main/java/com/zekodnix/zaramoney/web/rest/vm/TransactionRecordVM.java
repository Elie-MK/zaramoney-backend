package com.zekodnix.zaramoney.web.rest.vm;

import jakarta.validation.constraints.*;
import com.zekodnix.zaramoney.domain.enumeration.Currency;
import com.zekodnix.zaramoney.domain.enumeration.TransactionType;
import java.math.BigDecimal;

public class TransactionRecordVM {

    @NotNull
    private TransactionType transactionType;

    @NotNull
    @DecimalMin(value = "1")
    private BigDecimal sendAmount;

    @Size(max = 255)
    private String description;

    @NotNull
    @Size(min = 8, max = 16)
    private String receiverAccountNumber;

    @NotNull
    private Currency currencySendAmount;

    @NotNull
    private Currency currencyReceiveAmount;

    /** Unique per request (e.g. a UUID generated by the app); reusing it replays the original result. */
    @NotBlank
    @Size(min = 8, max = 128)
    private String idempotencyKey;

    /** Ignored (kept so older app versions still deserialize); the server knows which endpoint was called. */
    private String endpoint;

    /** Transaction PIN (4 to 6 digits), set with PUT /api/plus/security/pin. Replaces the login password. */
    @NotNull
    @Pattern(regexp = "\\d{4,6}")
    private String pin;

    public TransactionRecordVM() {
    }

    public TransactionRecordVM(TransactionType transactionType, BigDecimal sendAmount, String description, String receiverAccountNumber, Currency currencySendAmount, Currency currencyReceiveAmount, String idempotencyKey, String endpoint, String pin) {
        this.transactionType = transactionType;
        this.sendAmount = sendAmount;
        this.description = description;
        this.receiverAccountNumber = receiverAccountNumber;
        this.currencySendAmount = currencySendAmount;
        this.currencyReceiveAmount = currencyReceiveAmount;
        this.idempotencyKey = idempotencyKey;
        this.endpoint = endpoint;
        this.pin = pin;
    }

    public TransactionType getTransactionType() {
        return transactionType;
    }

    public void setTransactionType(TransactionType transactionType) {
        this.transactionType = transactionType;
    }

    public BigDecimal getSendAmount() {
        return sendAmount;
    }

    public void setSendAmount(BigDecimal sendAmount) {
        this.sendAmount = sendAmount;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getReceiverAccountNumber() {
        return receiverAccountNumber;
    }

    public void setReceiverAccountNumber(String receiverAccountNumber) {
        this.receiverAccountNumber = receiverAccountNumber;
    }

    public Currency getCurrencySendAmount() {
        return currencySendAmount;
    }

    public void setCurrencySendAmount(Currency currencySendAmount) {
        this.currencySendAmount = currencySendAmount;
    }

    public Currency getCurrencyReceiveAmount() {
        return currencyReceiveAmount;
    }

    public void setCurrencyReceiveAmount(Currency currencyReceiveAmount) {
        this.currencyReceiveAmount = currencyReceiveAmount;
    }

    public String getIdempotencyKey() {
        return idempotencyKey;
    }

    public void setIdempotencyKey(String idempotencyKey) {
        this.idempotencyKey = idempotencyKey;
    }

    public String getEndpoint() {
        return endpoint;
    }

    public void setEndpoint(String endpoint) {
        this.endpoint = endpoint;
    }

    public String getPin() {
        return pin;
    }

    public void setPin(String pin) {
        this.pin = pin;
    }
}
